"""Crash recovery: restore the latest snapshot, then verify the events written after it.

The tail (events stored after the snapshot) is regenerated from the snapshot and compared
event by event. Only when it matches exactly is the simulation attached to the database, so a
disagreement leaves the database untouched.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass

from ai_island.config import AssetsConfig
from ai_island.llm.errors import ReplayMissingError
from ai_island.sim import Simulation
from ai_island.storage.db import DatabaseError, RunDB


class RecoveryError(Exception):
    """The stored events after the last snapshot do not match a replay of the snapshot."""


@dataclass(frozen=True)
class RecoveryInfo:
    snapshot_tick: int
    tail_events: int
    end_tick: int


def recover(
    db: RunDB,
    assets: AssetsConfig | None = None,
    setup: Callable[[Simulation], None] | None = None,
) -> tuple[Simulation, RecoveryInfo]:
    """The simulation at the end of the stored run, attached to ``db``.

    ``setup`` (optional) configures the new simulation before anything runs (the AI adapters,
    the broker's sleep/wall hooks, the wait hook). With AI seats the stored tail is replayed
    from the stored replies only (a missing reply is an error), and afterwards the run
    continues with reuse-first: no stored reply is ever requested again.
    """
    snapshot = db.latest_snapshot()
    if snapshot is None:
        raise DatabaseError(f"{db.path} has no snapshot")
    sim = Simulation.from_snapshot(snapshot, assets=assets)
    if setup is not None:
        setup(sim)
    tail = db.events_after(snapshot.last_event_id or 0)
    if not tail:
        sim.attach(db, already_stored=True)
        return sim, RecoveryInfo(snapshot.tick, 0, sim.world.tick)
    end_tick = tail[-1][1].tick
    sim.replaying = True
    sim.replay_db = db
    try:
        try:
            sim.run(max(0, end_tick - sim.world.tick))
        except ReplayMissingError as exc:
            raise RecoveryError(f"the replay needs an AI reply that is not stored: {exc}") from exc
        regenerated = sim.world.events
        for index, (event_id, stored) in enumerate(tail):
            if index >= len(regenerated):
                raise RecoveryError(
                    f"stored event {event_id} (tick {stored.tick}, {stored.type}) "
                    "was not regenerated by the replay"
                )
            got = regenerated[index]
            if (got.tick, got.type, got.payload_json()) != (
                stored.tick,
                stored.type,
                stored.payload_json(),
            ):
                raise RecoveryError(
                    f"event {event_id} differs: stored tick {stored.tick} {stored.type}, "
                    f"replay tick {got.tick} {got.type}"
                )
        if len(regenerated) > len(tail):
            extra = regenerated[len(tail)]
            raise RecoveryError(
                f"the replay produced an event the database does not have after event "
                f"{tail[-1][0]} (tick {extra.tick}, {extra.type}); the stored tail ends mid-tick"
            )
    finally:
        sim.replaying = False
        sim.replay_db = None
    sim.attach(db, already_stored=True)
    return sim, RecoveryInfo(snapshot.tick, len(tail), sim.world.tick)
